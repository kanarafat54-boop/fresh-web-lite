import type { Evidence } from "./FreshAIArchitecture.js";

/** Transparent extractive fallback when the native Fresh model is unavailable. */
export function synthesizeFreshPlatformAnswer(goal: string, evidence: Evidence[]): string | null {
  const query = goal.toLowerCase();
  const stop = new Set(["what", "which", "when", "where", "explain", "about", "list", "available", "there", "this", "that", "from", "into", "have", "does", "with", "your"]);
  const tokens = Array.from(new Set(query.split(/[^a-z0-9]+/).filter((word) => word.length > 3 && !stop.has(word))));
  const freshFlowQuestion = /\bfresh flow\b/.test(query);
  const mediaFormatsQuestion = /media formats|formats available|types of media/.test(query);
  const ranked = evidence.map((item) => {
    const claim = typeof item.claim === "string" ? item.claim.trim() : "";
    const lower = claim.toLowerCase();
    const overlap = tokens.reduce((score, token) => score + (lower.includes(token) ? 1 : 0), 0);
    const flowSignal = /fresh flow|shorts|long videos|news\s*\/\s*posts|ar\s*\/\s*vr|podcasts|others/.test(lower);
    const formatSignal = /shorts|long videos|news\s*\/\s*posts|ar\s*\/\s*vr|podcasts|others/.test(lower);
    const score = overlap + (freshFlowQuestion && flowSignal ? 5 : 0) + (mediaFormatsQuestion && formatSignal ? 5 : 0);
    return { item, claim, score, flowSignal };
  }).filter((entry) => entry.claim && entry.score > 0 && (!freshFlowQuestion || entry.flowSignal || entry.score >= 3))
    .sort((a, b) => b.score - a.score);
  const selected = ranked.slice(0, 4);
  if (!selected.length) return null;
  const bullets = selected.map(({ claim, item }) => {
    const source = typeof item.source === "string" && item.source.trim() ? item.source.trim() : "Fresh Web Lite project knowledge";
    return "- " + claim.slice(0, 650) + " (Source: " + source + ")";
  });
  const heading = freshFlowQuestion ? "Fresh Flow — summary from retrieved Fresh Web Lite project documentation" : "Summary from retrieved Fresh Web Lite project documentation";
  const caveat = "The Fresh Unified native language-model endpoint is not currently ready, so this is a source-based extractive summary, not a response generated by a trained Fresh model.";
  return heading + "\n\n" + bullets.join("\n") + "\n\n" + caveat;
}
