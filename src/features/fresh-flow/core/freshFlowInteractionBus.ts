import { supabase } from "../../../lib/supabase";
import { writeStatefulInteraction } from "../../../core/interactions/statefulInteractionWrite";

export type FreshFlowInteractionInput = {
  actorId: string;
  targetType: string;
  targetId: string;
  interactionType: string;
  interactionValue?: string | null;
  parentId?: string | null;
  payload?: Record<string, unknown>;
  stateKey?: string | null;
};

export async function persistFreshFlowInteraction(input: FreshFlowInteractionInput) {
  const row = {
    actor_id: input.actorId,
    target_type: input.targetType,
    target_id: input.targetId,
    interaction_type: input.interactionType,
    interaction_value: input.interactionValue ?? null,
    parent_id: input.parentId ?? null,
    payload: input.payload ?? {},
  };

  // state_key is generated by the database from interaction_type, so a state is requested, never written.
  const result = input.stateKey
    ? await writeStatefulInteraction(supabase, row)
    : await supabase.from("universal_interactions").insert(row);

  if (result.error) throw new Error(`Fresh Flow interaction failed: ${result.error.message}`);
}

export async function broadcastFreshFlowEvent(
  userId: string | null,
  event: Record<string, unknown>,
) {
  const topic = userId ? `fresh-flow:user:${userId}` : "fresh-flow:media";
  const channel = supabase.channel(topic);
  try {
    await channel.send({ type: "broadcast", event: "fresh-flow", payload: event });
  } finally {
    await supabase.removeChannel(channel);
  }
}
