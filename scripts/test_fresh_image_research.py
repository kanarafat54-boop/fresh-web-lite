"""End-to-end CPU smoke test for the Fresh-owned image research scaffold.

Uses tiny synthetic test fixtures created by this test; no external dataset or
pretrained weights are downloaded. This only validates the research plumbing,
not image quality or production readiness.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
TRAINER = ROOT / "training" / "fresh_image_research.py"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> int:
    with tempfile.TemporaryDirectory(prefix="fresh-image-smoke-") as temp:
        work = Path(temp)
        data = work / "dataset"
        data.mkdir()
        records = []
        for index, (caption, color) in enumerate([
            ("a simple red square", (220, 25, 25)),
            ("a simple blue square", (25, 25, 220)),
        ]):
            image_path = data / f"synthetic-{index}.png"
            image = Image.new("RGB", (24, 24), (245, 245, 245))
            draw = ImageDraw.Draw(image)
            draw.rectangle((4, 4, 19, 19), fill=color)
            image.save(image_path, format="PNG")
            records.append({
                "record_id": f"synthetic-{index}",
                "asset_sha256": sha256(image_path),
                "relative_path": image_path.name,
                "split": "train",
                "source_type": "created_by_fresh",
                "rights_basis": "synthetic test fixture generated by this test",
                "personal_data_review": "cleared",
                "caption": caption,
            })

        now = datetime.now(timezone.utc).isoformat()
        manifest = {
            "schema_version": "1.0.0",
            "dataset_id": "fresh-image-ci-smoke",
            "owner": "Fresh AI",
            "created_at": now,
            "license_review": {
                "review_status": "approved",
                "reviewed_by": "automated-smoke-test",
                "reviewed_at": now,
                "evidence_uri": "local synthetic fixtures generated in the test",
            },
            "records": records,
        }
        manifest_path = work / "manifest.json"
        manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        checkpoint = work / "research.pt"
        png = work / "sample.png"

        subprocess.run([
            sys.executable, str(TRAINER), "train",
            "--manifest", str(manifest_path),
            "--dataset-root", str(data),
            "--output", str(checkpoint),
            "--steps", "2",
            "--batch-size", "1",
            "--seed", "7",
        ], check=True, cwd=ROOT)

        metadata_path = checkpoint.with_suffix(checkpoint.suffix + ".json")
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        assert metadata["modelId"] == "fresh-image-research-0"
        assert metadata["productionReady"] is False
        assert metadata["pretrainedWeightsUsed"] is False
        assert metadata["thirdPartyInferenceUsed"] is False
        assert metadata["paidComputeUsed"] is False
        assert metadata["steps"] == 2
        assert metadata["checkpointSha256"] == sha256(checkpoint)

        subprocess.run([
            sys.executable, str(TRAINER), "sample",
            "--checkpoint", str(checkpoint),
            "--prompt", "a red square",
            "--output", str(png),
        ], check=True, cwd=ROOT)
        with Image.open(png) as result:
            result.verify()
        with Image.open(png) as result:
            assert result.format == "PNG"
            assert result.size == (16, 16)
            assert result.mode == "RGB"
        print("PASS: synthetic dataset -> fresh training -> checkpoint verification -> genuine PNG sample")
        print("NOTE: research plumbing only; this does not validate image quality or production readiness")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
