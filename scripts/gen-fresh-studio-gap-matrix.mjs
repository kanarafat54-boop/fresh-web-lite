// Generates docs/fresh-flow-studio-gap-matrix.md from the real profiles and editor list.
import { writeFileSync } from "node:fs";
import { FRESH_FLOW_STUDIO_PROFILES } from "../src/features/fresh-flow/core/freshFlowStudioIntegration.ts";
import { KINDS_WITH_EDITOR } from "../src/features/fresh-studio/shared/studioNav.ts";

const EDITOR_NOTE = {
  video: "Video editor: timeline, captions, stickers, export (server render for long files).",
  image: "Photo editor: adjust, rotate, PNG export.",
  audio: "Audio editor: trim, fades, level, chapters, WAV export.",
  custom: "Writing editor: title, text, outline, sources, checks, Markdown/text export (text only).",
  podcast: "Audio editor: trim, fades, level, chapters, WAV export.",
};
const NOT_CONNECTED = "Studio saves the project; sending it to this system's feed is not wired up from here.";
const BLOCK = {
  "domain-work-required": "No editor for this kind yet. Creates a planning project that links to the domain's tools.",
  "provider-required": "Needs a live ingest/egress provider (paid infrastructure; not approved). Planning project only.",
  "device-required": "Needs device/WebXR work and test hardware. Planning project only.",
};
// The writing editor covers text work only; these systems need more than text.
const TEXT_ONLY_GAPS = {
  "interactive-experiences": "Needs a sandboxed interactive runtime; the writing editor does not build interactive content.",
  learn: "Text lessons only: no course structure, quizzes or assessments.",
  "books-reading": "Text chapters only: no ebook packaging or comics layout.",
  "creator-channels": "Text only: no channel page layout or collections.",
  communities: "Text only: no community targeting or moderation tools.",
};
const hasEditorFor = (p) => KINDS_WITH_EDITOR.includes(p.mediaKind) && p.systemId !== "interactive-experiences";
const rows = FRESH_FLOW_STUDIO_PROFILES.map((p) => {
  const editor = hasEditorFor(p);
  const status = editor ? "Editor exists" : p.implementation === "domain-work-required" ? "Planning project only" : "Blocked";
  const detail = editor ? `${EDITOR_NOTE[p.mediaKind]} ${TEXT_ONLY_GAPS[p.systemId] ?? ""} ${NOT_CONNECTED}` : (TEXT_ONLY_GAPS[p.systemId] ?? BLOCK[p.implementation] ?? "Planning project only.");
  return `| ${p.systemId} | ${p.mediaKind} | ${status} | ${detail} |`;
});
const n = FRESH_FLOW_STUDIO_PROFILES.filter(hasEditorFor).length;
writeFileSync(new URL("../docs/fresh-flow-studio-gap-matrix.md", import.meta.url), `# Fresh Flow × Creator Studio gap matrix

Generated by \`node --experimental-strip-types scripts/gen-fresh-studio-gap-matrix.mjs\` from the profiles and editor list. Do not edit by hand.

${n} of ${rows.length} systems open a real editor. Studio does not publish into any domain feed itself yet.

| System | Media kind | Status | What exists / what is missing |
| --- | --- | --- | --- |
${rows.join("\n")}
`);
console.log(`${n}/${rows.length} with editor`);
