// Generates an idempotent SQL migration that teaches Fresh AI the master matrix:
// one knowledge row per module and two training examples per module.
// No outside AI involved. Re-run whenever the matrix changes.
//   node scripts/generate-fresh-knowledge-from-matrix.mjs [matrix.csv] [out.sql]
import fs from "node:fs";

const [, , csvPath = "docs/FRESH_WEB_LITE_MASTER_MATRIX.csv", outPath] = process.argv;

function parseCsv(text) {
  const rows = []; let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((x) => x !== "")) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== "" || row.length) { row.push(field); if (row.some((x) => x !== "")) rows.push(row); }
  return rows;
}

const q = (v) => "'" + String(v ?? "").trim().replace(/'/g, "''") + "'";
const [header, ...data] = parseCsv(fs.readFileSync(csvPath, "utf8"));
const col = (name) => header.indexOf(name);
for (const need of ["#", "Category", "Module", "Purpose", "Phase", "Priority", "Status", "Notes"])
  if (col(need) < 0) throw new Error(`Matrix is missing column: ${need}`);

const values = data
  .filter((r) => /^\d+$/.test((r[col("#")] || "").trim()))
  .map((r) => ` (${Number(r[col("#")])},${["Category", "Module", "Purpose", "Phase", "Priority", "Status", "Notes"].map((n) => q(r[col(n)])).join(",")})`)
  .join(",\n");

const sql = `-- Generated by scripts/generate-fresh-knowledge-from-matrix.mjs from ${csvPath}.
-- Idempotent. Teaches Fresh AI the master matrix with no outside AI involved.
with m(n, category, module, purpose, phase, priority, status, notes) as (values
${values}
), s as (
  select m.*,
    case status when 'IN PROGRESS' then 'in progress: partly built and not yet complete'
                when 'PLANNED' then 'planned and not built yet'
                when 'LIVE VERIFIED' then 'live and verified'
                else lower(status) end as status_text,
    case status when 'IN PROGRESS' then 'Partly. ' || module || ' is in progress and not complete yet.'
                when 'PLANNED' then 'No. ' || module || ' is planned and not built yet.'
                when 'LIVE VERIFIED' then 'Yes. ' || module || ' is live and verified.'
                else module || ' status: ' || lower(status) || '.' end as availability
  from m
), k as (
  insert into public.fresh_ai_knowledge (user_id, project_id, title, content, modality, source, provenance, truth_state, confidence, metadata)
  select null, 'fresh-web-lite-platform', 'Master matrix: ' || module,
    module || ': ' || purpose || '. Category: ' || category || '. Phase ' || phase || '. Priority ' || priority || '. Status: ' || status_text || '.'
      || case when coalesce(notes, '') <> '' then ' Notes: ' || notes || '.' else '' end,
    'text', '${csvPath}', jsonb_build_object('kind', 'first-party', 'matrix_row', n), 'KNOWN', 0.9,
    jsonb_build_object('dataset', 'master-matrix-v1', 'status', status)
  from s
  where not exists (select 1 from public.fresh_ai_knowledge x where x.project_id = 'fresh-web-lite-platform' and x.user_id is null and x.title = 'Master matrix: ' || s.module)
  returning 1
)
insert into public.fresh_ai_training_examples (example_type, input_text, output_text, labels, source, quality_score, safety_score, dataset_version)
select 'instruction-response', t.input, t.output, jsonb_build_object('domain', 'master-matrix', 'module', s.module), 'first-party-platform-docs', 0.9, 1.0, 'master-matrix-v1'
from s cross join lateral (values
  ('What is ' || s.module || '?', s.module || ': ' || s.purpose || '. It is ' || s.status_text || '.'),
  ('Is ' || s.module || ' available today?', s.availability)
) as t(input, output)
where not exists (select 1 from public.fresh_ai_training_examples e where e.dataset_version = 'master-matrix-v1' and e.input_text = t.input);
`;

if (outPath) { fs.writeFileSync(outPath, sql); console.log(`Wrote ${outPath}: ${data.length} modules`); }
else process.stdout.write(sql);
