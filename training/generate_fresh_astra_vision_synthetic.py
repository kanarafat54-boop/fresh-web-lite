"""Generate Fresh-owned, non-personal geometric scenes for Astra vision smoke training."""
from __future__ import annotations
import argparse
import hashlib
import json
import random
from pathlib import Path
from PIL import Image, ImageDraw

SHAPES = ("circle", "square", "triangle")
COLOURS = {"blue": (40, 100, 220), "green": (35, 165, 85), "red": (220, 55, 55), "yellow": (235, 190, 35)}

def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()

def generate_dataset(output: Path, count: int = 240, seed: int = 20261030) -> Path:
    if count < 60 or count > 5000 or count % 6:
        raise ValueError("count must be a multiple of six between 60 and 5000")
    rng = random.Random(seed)
    root = output.resolve()
    root.mkdir(parents=True, exist_ok=True)
    records = []
    sizes = {"train": int(count * 0.75), "validation": int(count * 0.125)}
    sizes["test"] = count - sizes["train"] - sizes["validation"]
    splits = [split for split, size in sizes.items() for _ in range(size)]
    rng.shuffle(splits)
    for index in range(count):
        shape = SHAPES[index % len(SHAPES)]
        colour_name = tuple(COLOURS)[(index // len(SHAPES)) % len(COLOURS)]
        colour = COLOURS[colour_name]
        background = (rng.randint(238, 255), rng.randint(238, 255), rng.randint(238, 255))
        image = Image.new("RGB", (64, 64), background)
        draw = ImageDraw.Draw(image)
        size = rng.randint(24, 42)
        x, y = rng.randint(5, 59 - size), rng.randint(5, 59 - size)
        if shape == "circle":
            draw.ellipse((x, y, x + size, y + size), fill=colour)
        elif shape == "square":
            draw.rectangle((x, y, x + size, y + size), fill=colour)
        else:
            draw.polygon(((x + size // 2, y), (x + size, y + size), (x, y + size)), fill=colour)
        relative = Path("images") / f"astra-synthetic-{index:05d}.png"
        destination = root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        image.save(destination, format="PNG", optimize=True)
        records.append({
            "record_id": f"astra-synth-{index:05d}", "relative_path": relative.as_posix(),
            "asset_sha256": sha256_file(destination), "split": splits[index],
            "shape_label": shape, "colour_label": colour_name, "source_type": "created_by_fresh",
            "rights_basis": "Fresh-owned procedural synthetic image generated by the Fresh Astra vision pilot",
            "personal_data_review": "cleared",
        })
    manifest = {
        "schema_version": "fresh-astra-vision-dataset-v1", "dataset_id": f"fresh-astra-shapes-{seed}",
        "owner": "Fresh AI", "created_at": "2026-10-30T00:00:00Z",
        "generator": "fresh-astra-synthetic-vision-v1", "seed": seed,
        "license_review": {"review_status": "approved", "reviewed_by": "Fresh AI synthetic-data policy",
            "reviewed_at": "2026-10-30T00:00:00Z", "evidence_uri": "internal://fresh-ai/synthetic-vision-generator-v1"},
        "records": records,
    }
    manifest_path = root / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest_path

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True)
    parser.add_argument("--count", type=int, default=240)
    parser.add_argument("--seed", type=int, default=20261030)
    args = parser.parse_args()
    manifest = generate_dataset(Path(args.output), args.count, args.seed)
    print(f"manifest={manifest}")
    print(f"records={args.count}")
    print("source=Fresh-owned synthetic geometric images; no personal data or third-party weights")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
